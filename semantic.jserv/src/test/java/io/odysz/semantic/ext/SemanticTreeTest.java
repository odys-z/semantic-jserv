/**
 * Tests of {@link SemanticTree#onModifyTree(String, TreeSemantics, TreeMod, io.odysz.semantics.IUser)}.
 *
 * <p>Each case clears table doctree in the main test db (src/test/res/jserv-main.db), inserts the fixture,
 * then for each step calls onModifyTree() and verifies the returned reload root, and the whole tree loaded
 * back from DB: parent, sort, fullpath of each row, and the indents of the built forest.</p>
 *
 * Test data: src/test/res/stree/stree-cases.json, generated by gen.py in the same folder.
 *
 * @since 1.5.20
 */
class SemanticTreeTest {
	static final String conn = "main-sqlite";
	static final String json = "src/test/res/stree/stree-cases.json";
	static final String webinf = "src/test/res/WEB-INF";

	static StreeCases jcases;
	static TreeSemantics sm;

	@BeforeAll
	static void init() throws Exception {
		Connects.init(webinf);
		DatasetCfg.init(webinf);
		jcases = Anson.fromPath(json);
		sm = DatasetCfg.getTreeSemtcs(jcases.sk);
	}

	/** The fixture alone: verifies loading / building the forest, before any modification. */
	@Test
	void testFixture() throws Exception {
		resetTable();
		assertTree("fixture", jcases.fixtureTree);
	}

	@TestFactory
	Stream<DynamicTest> testModifyTree() {
		return jcases.steps.stream()
			.map(c -> DynamicTest.dynamicTest(String.format("%s %s -> %s[%s]", c.req.a(), c.req.nid, c.req.toParent, c.req.toIndex), () -> runCase(c)));
	}

	static void runCase(StreeStep c) throws Exception {
		resetTable();

		String msg = String.format("step %s %s -> %s[%s]", c.req.a(), c.req.nid, c.req.toParent, c.req.toIndex);

		AnDatasetResp res = null;
		AnDatasetReq req = c.req;
		IUser testRobot = new IUser() {
			@Override
			public TableMeta meta(String... connId) throws TransException, SQLException { return null; }

			@Override
			public long touchedMs() { return 0; }

			@Override
			public String uid() { return "stree-tester"; }

			@Override
			public IUser logAct(String funcName, String funcId) { return null; }
		};

		SemanticTree stree = new SemanticTree();
		if (eq(AnDatasetReq.A.insrt, req.a()))
			res = stree.onInsertTree(conn, sm, req, testRobot);
		else if (eq(AnDatasetReq.A.umove, req.a()))
			res = stree.onMoveTree(conn, sm, req, testRobot);
		else if (eq(AnDatasetReq.A.del, req.a()))
			res = stree.onDelTree(conn, sm, req, testRobot);
		else
			fail("Unknow A: " + req.a());

		assertEquals(c.rejected, res.rejected(), msg + ", rejected");

		if (c.rejected == null) {
			assertEquals(c.root, res.root(), msg + ", reload root");
			assertTrue(res.forest().size() > 0, "update forest size");
		}

		assertTree(msg, c.expectings);
	}

	static void resetTable() throws Exception {
		ArrayList<String> sqls = new ArrayList<String>();
		sqls.addAll(jcases.ddl);
		sqls.addAll(jcases.fixture);
		Connects.commit(conn, null, sqls);
	}

	/** IndentFlag to text icon, the same as anclient's defltIcons (space: spacex) */
	static final HashMap<String, String> icons = new HashMap<String, String>() {
		private static final long serialVersionUID = 1L;
		{	put("childi", "├"); put("childx", "L"); put("vlink", "|"); put("space", ".");
			put("expand", "T"); put("collapse", "+"); put("hlink", "-"); put("deflt", ".");
		}};

	/**
	 * Load the table back, build the forest, and compare line by line, in depth-first order:
	 * "indent-icons nid parent sort fullpath", e.g. "| L a22 a2 2 01.01.02.02"; a root's icons are "-".
	 */
	static void assertTree(String msg, List<String> expect) throws Exception {
		AnResultset rs = Connects.select(conn, String.format(
				"select nid, parent, sort, fullpath, nodetype, text from %s order by fullpath",
				jcases.table));

		List<AnTreeNode> forest = DatasetHelper.buildForest(rs, sm);

		ArrayList<String> actual = new ArrayList<String>();
		for (AnTreeNode root : forest)
			lines(msg, root, null, actual);

		assertEquals(String.join("\n", expect), String.join("\n", actual), msg + ", tree");
	}

	static void lines(String msg, TreeIndenode n, String parentId, List<String> out) {
		// the parent in DB must be where the builder put the node
		assertEquals(parentId, n.get("parent"), msg + ", parent of " + n.id());

		List<?> indents = n.indents();
		out.add(String.format("%s %s %s %s %s",
				indents == null || indents.isEmpty() ? "-"
				: indents.stream().map(f -> icons.get(String.valueOf(f))).collect(Collectors.joining(" ")),
				n.id(), parentId == null ? "-" : parentId, n.get("sort"), n.get("fullpath")));

		List<?> children = n.children();
		if (children != null)
			for (Object ch : children)
				lines(msg, (TreeIndenode) ch, n.id(), out);
	}
}
