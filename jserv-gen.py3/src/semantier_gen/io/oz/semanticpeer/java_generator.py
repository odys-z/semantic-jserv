import re
from dataclasses import dataclass
from pathlib import Path
from typing import cast, List

from anson.io.odysz.anson import Anson
from anson.io.odysz.common import Utils, LangExt
from semanticshare.io.odysz.reflect import AnsonBodyAst, PeerSettings, AnsonAst, AnsonJavaEnumAst


J_prims = {
    'string': 'String', 'String': 'String', 'java.lang.String': 'String',
    'int': 'int', 'long': 'long', 'short': 'short',
    'float': 'float', 'double': 'double',
    'boolean': 'boolean', 'bool': 'boolean',
}
'''
AST dataAnclass -> Java type, the Java equivalent of Primtypes.C20.
'''

J_boxed = {'int': 'Integer', 'long': 'Long', 'short': 'Short', 'float': 'Float',
           'double': 'Double', 'boolean': 'Boolean'}

def j_type(dataAnclass: str) -> tuple[str, set[str]]:
    '''
    The Java equivalent of py_generator.c_type().
    E.g. 'map<string, string' -> HashMap<String, String>, 'list<string' -> ArrayList<String>.
    :param dataAnclass:
    :return: (java type, imports)
    '''
    imports: set[str] = set()

    def elem(t: str) -> str:
        t = t.strip()
        j = J_prims.get(t, t.split('.')[-1])
        if '.' in t and t not in J_prims:
            imports.add(t)
        return J_boxed.get(j, j)

    m = re.fullmatch(r'map<\s*([^,]+),\s*(.+?)>?', dataAnclass)
    if m:
        imports.add('java.util.HashMap')
        return f'HashMap<{elem(m.group(1))}, {elem(m.group(2))}>', imports

    m = re.fullmatch(r'list<\s*(.+?)>?', dataAnclass)
    if m:
        imports.add('java.util.ArrayList')
        return f'ArrayList<{elem(m.group(1))}>', imports

    if dataAnclass in J_prims:
        return J_prims[dataAnclass], imports

    if '.' in dataAnclass:
        imports.add(dataAnclass)
    return dataAnclass.split('.')[-1], imports

@dataclass
class JavaLines:
    '''
    The class name is the last part of dataAnclass, the same as the C++ class.

    Java-only field keys, ignored by cpp_generator:
        "javaType"  : override the mapped type, e.g. "String[]" for "list<string"
        "default"   : initializer expression, e.g. "8900", "\\"rtd-0.8\\""
        "ignoreFrom": true, -> @AnsonField(ignoreFrom=true)
        "ignoreTo"  : true, -> @AnsonField(ignoreTo=true)
    '''

    package: str = 'package {};\n\n'

    imports: str = 'import {};\n'

    class_decl: str = '''
/**
 * Generated by semantier_gen from {0}. Do not edit.
 * <p>AST type: {1}</p>
 */
public class {2} extends {3} {{

'''
    '''
    E.g.
    /**
     * Generated by semantier_gen from appsettings.ast.json. Do not edit.
     * <p>AST type: io.oz.jserv.docs.syn.singleton.AppSettings</p>
     */
    public class AppSettings2 extends Anson {
    '''

    field_flags: str = '\t@AnsonField({})\n'

    field: str = '\tpublic {} {}{};\n'

    ctor0: str = '\n\tpublic {}() {{ }}\n'

    end_class: str = '}\n'

    def javacode(self, ast: AnsonAst, astjson: str) -> List[str]:
        pkg, _, _ = ast.dataAnclass.rpartition('.')
        base_pkg, _, base = ast.baseAnclass.rpartition('.')

        imports = {ast.baseAnclass} if base_pkg != pkg else set()
        fields = []
        for fn, fd in ast.fields.items():
            jt, imps = j_type(fd['dataAnclass'])
            if 'javaType' in fd:
                jt = fd['javaType']
            else:
                imports |= imps

            flags = [f'{k}=true' for k in ('ignoreFrom', 'ignoreTo') if fd.get(k)]
            if len(flags) > 0:
                imports.add('io.odysz.anson.AnsonField')
                fields.append(self.field_flags.format(', '.join(flags)))

            fields.append(self.field.format(jt, fn, f' = {fd["default"]}' if 'default' in fd else ''))

        return [self.package.format(pkg),
                *[self.imports.format(i) for i in sorted(imports)],
                self.class_decl.format(Path(astjson).name, ast.dataAnclass, ast.c_class(), base),
                *fields,
                self.ctor0.format(ast.c_class()),
                self.end_class]


def gen_java_peer(settings: PeerSettings) -> Path:
    '''
    Generate Java data classes (fields only) of settings.ansons, into PeerSettings.java_gen,
    the output folder. The actual generated java file path will be appended with the package name.

    Only plain Anson types are generated. AnsonBodyAst and AnsonJavaEnumAst are ignored,
    which can be in settings.ansons, extended by py_generator.gen_cpp_peer2().

    :param settings:
    :return: The new PeerSettings.java_gen, None if it is not configured.
    '''
    if LangExt.isblank(settings.java_gen):
        return None

    javalines = JavaLines()
    gen_root = Path(settings.java_gen)

    for astjson in settings.ansons:
        astpth = Path(settings.ast_folder) / astjson
        if not astpth.exists():
            Utils.warn('Cannot find file ' + str(astpth))
            continue

        ast: AnsonAst = cast(AnsonAst, Anson.from_file(str(astpth)))
        if isinstance(ast, (AnsonBodyAst, AnsonJavaEnumAst)):
            continue

        java_pth = gen_root / ast.dataAnclass.rpartition('.')[0].replace('.', '/') / f'{ast.c_class()}.java'
        java_pth.parent.mkdir(parents=True, exist_ok=True)

        with open(java_pth, 'w') as gen:
            gen.writelines(javalines.javacode(ast, astjson))

    return gen_root
